import { readFile, writeFile, mkdir } from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const src = path.join(root, 'scripts', 'install-agent.ps1');
const outDir = path.join(root, 'netlify', 'functions', 'lib');
const outFile = path.join(outDir, 'install-template.mjs');

const script = await readFile(src, 'utf8');
await mkdir(outDir, { recursive: true });
await writeFile(outFile, `// Generated by scripts/build-template.mjs - jangan edit manual\nexport default ${JSON.stringify({ script })};\n`);
console.log('Template installer dibuat:', path.relative(root, outFile));
